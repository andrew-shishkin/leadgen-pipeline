// Разбор и склонение русских имён. Всё кодом: правила детерминированные,
// бесплатные и не зависят от того, какая нейросеть подключена.

/** Распространённые русские имена.
 *
 *  Нужны, чтобы понять порядок слов в «Ирина Шамина». Окончаний для этого
 *  не хватает: «Ирина» оканчивается на -ина ровно как фамилия «Шамина»,
 *  а «Цыкун» на фамилию не похож вовсе. Список закрывает подавляющее
 *  большинство российских выгрузок, а на редких именах порядок остаётся
 *  прежним — как записано в файле. */
