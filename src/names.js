export const isFirstName = (w) => FIRST_NAMES.has(String(w ?? '').toLowerCase().replace('ё', 'ё'));

/** Отчество узнаётся по окончанию — оно однозначное. */
export const isPatronymic = (w) =>
  /(ович|евич|ьич|овна|евна|ична|инична)$/i.test(w ?? '') && (w ?? '').length > 4;

// ─────────────────────────── Дательный падеж ───────────────────────────
// «Кому» в обращении: Ирина → Ирине, Ксения → Ксении, Роман → Роману.

/** Имена, которые не склоняются: заимствованные и оканчивающиеся на гласную,
 *  кроме -а/-я. «Рон», «Марк» склоняются, а «Мери», «Гоар» — нет. */
const INDECLINABLE = /[еиоуыэюё]$/i;

/** Беглая гласная и другие исключения, которые правилом не берутся. */
const IRREGULAR = {
  'пётр': 'Петру', 'петр': 'Петру', 'лев': 'Льву', 'павел': 'Павлу',
  'фёдор': 'Фёдору', 'федор': 'Федору', 'любовь': 'Любови',
};

/** Дательный падеж одного слова — имени или отчества. */
export function dativeWord(w) {
  const s = String(w ?? '').trim();
  if (!s) return '';
  const low = s.toLowerCase();
  if (IRREGULAR[low]) return IRREGULAR[low];

  // отчества
  if (/(ович|евич|ьич)$/i.test(s)) return s + 'у';
  if (/(овна|евна|ична|инична)$/i.test(s)) return s.slice(0, -1) + 'е';

  if (/ия$/i.test(s)) return s.slice(0, -1) + 'и';      // Ксения → Ксении
  if (/ья$/i.test(s)) return s.slice(0, -1) + 'е';      // Наталья → Наталье
  if (/[ая]$/i.test(s)) return s.slice(0, -1) + 'е';    // Ирина → Ирине, Оля → Оле
  if (/й$/i.test(s)) return s.slice(0, -1) + 'ю';       // Сергей → Сергею
  if (/ь$/i.test(s)) return s.slice(0, -1) + 'ю';       // Игорь → Игорю
  if (INDECLINABLE.test(s)) return s;                    // Мери → Мери
  return s + 'у';                                        // Роман → Роману
}

/** Дательный для «Имя Отчество» целиком. */
export const dativeFio = (nominative) => String(nominative ?? '').trim()
  .split(/\s+/).filter(Boolean).map(dativeWord).join(' ');

// ─────────────────────────── Супервизор ───────────────────────────

/**
 * Проверка того, что нейросеть вернула для обращения в письме.
 *
 * Эти два поля уходят прямо в текст письма переменными, и ошибка в них
 * видна получателю. На живой выгрузке нейросеть путала имя с фамилией
 * («Ирина Шамина» → обращение «Шамина», дательный пустой), потому что
 * в промпте ей обещали формат «Фамилия Имя Отчество».
 *
 * Поэтому её ответ сверяется с разбором в коде:
 *   1. именительный должен совпасть с именем (и отчеством), а не с фамилией;
 *   2. дательный не должен быть пустым;
 *   3. дательный обязан отличаться от именительного, если имя склоняемое.
 *
 * Что не прошло проверку — заменяется склонением по правилам. Правила
 * покрывают не всё, поэтому нейросеть остаётся первой: у неё лучше
 * с редкими и нерусскими именами.
 */
export function superviseDecline({ expectedFirst, expectedPatronymic, nominative, dative }) {
  const want = [expectedFirst, expectedPatronymic].filter(Boolean).join(' ').trim();
  const norm = (x) => String(x ?? '').trim().toLowerCase().replace(/ё/g, 'е');
  const problems = [];

  if (!want) return { ok: !!dative, nominative, dative, problems: [] };

  if (norm(nominative) !== norm(want)) problems.push('именительный не совпал с именем');
  if (!String(dative ?? '').trim()) problems.push('дательный пустой');
  else if (norm(dative) === norm(want) && !INDECLINABLE.test(expectedFirst ?? ''))
    problems.push('дательный не отличается от именительного');

  if (!problems.length) return { ok: true, nominative, dative, problems };
  return { ok: false, nominative: want, dative: dativeFio(want), problems };
}
